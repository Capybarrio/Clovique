export const normalizeProductSearchQuery = (query) => {
  const normalizedQuery = normalizeText(query || "");

  if (!normalizedQuery) return "";

  const exactTranslatedNameMatch = Object.entries(
    productTranslations.names,
  ).find(
    ([, translatedName]) => normalizeText(translatedName) === normalizedQuery,
  );

  if (exactTranslatedNameMatch) return exactTranslatedNameMatch[0];

  const keywordMatch = searchKeywordMap.find(([ukrainianKeyword]) =>
    normalizedQuery.includes(ukrainianKeyword),
  );

  if (keywordMatch) return keywordMatch[1];

  const translatedNameMatch = Object.entries(productTranslations.names).find(
    ([, translatedName]) =>
      normalizeText(translatedName).includes(normalizedQuery),
  );

  if (translatedNameMatch) return translatedNameMatch[0];

  const valueMatch = Object.entries(productTranslations.values).find(
    ([, translatedValue]) =>
      normalizeText(translatedValue).includes(normalizedQuery),
  );

  if (valueMatch) return valueMatch[0];

  return query.trim();
};
