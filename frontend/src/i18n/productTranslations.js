const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const normalizeSpaces = (value) => value.replace(/\s+/g, " ").trim();

const translateEditedProductName = (value) => {
  if (!value) return value;

  const translatedValue = titleWordTranslations.reduce(
    (result, [pattern, replacement]) => result.replace(pattern, replacement),
    value,
  );

  if (translatedValue === value) return value;

  return normalizeSpaces(translatedValue)
    .replace(/\bчоловіча\b/i, "Чоловіча")
    .replace(/\bжіноча\b/i, "Жіноча")
    .replace(/\bфутболка\b/i, "футболка");
};

const translateEditedProductDescription = (value) => {
  if (!value) return value;

  const sentenceTranslatedValue = sentenceTranslations.reduce(
    (result, [source, replacement]) => result.replace(source, replacement),
    value,
  );

  if (sentenceTranslatedValue !== value) {
    return sentenceTranslatedValue;
  }

  const phraseTranslatedValue = descriptionPhraseTranslations.reduce(
    (result, [source, replacement]) => {
      const pattern =
        source instanceof RegExp
          ? source
          : new RegExp(escapeRegExp(source), "gi");

      return result.replace(pattern, replacement);
    },
    value,
  );

  return phraseTranslatedValue === value
    ? value
    : normalizeSpaces(phraseTranslatedValue);
};

export const translateProductText = (value, language, t) => {
  if (!value || language !== "uk") return value;

  const optionTranslation = t(`options.${value}`);

  return (
    productTranslations.names[value] ||
    productTranslations.descriptions[value] ||
    productTranslations.values[value] ||
    (optionTranslation === `options.${value}` ? value : optionTranslation)
  );
};

export const translateProduct = (product, language, t) => {
  if (!product || language !== "uk") return product;

  const cleanNameUk = product.nameUk?.trim();
  const cleanDescriptionUk = product.descriptionUk?.trim();
  const translationName =
    product.translationSource?.name === product.name
      ? product.translationSource.name
      : product.name;
  const descriptionTranslationName =
    product.translationSource?.description === product.description
      ? product.translationSource?.name
      : product.description;

  return {
    ...product,
    name:
      cleanNameUk ||
      productTranslations.names[translationName] ||
      translateEditedProductName(product.name),
    description:
      cleanDescriptionUk ||
      productTranslations.descriptions[descriptionTranslationName] ||
      productTranslations.descriptions[translationName] ||
      translateEditedProductDescription(product.description),
    material: translateProductText(product.material, language, t),
    colors: Array.isArray(product.colors)
      ? product.colors.map((color) => translateProductText(color, language, t))
      : product.colors,
  };
};

